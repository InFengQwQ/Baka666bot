# ================= Configuration =================
$ProjectRoot = Split-Path -Parent $PSScriptRoot
$WorkDir = $PSScriptRoot
$QQCandidates = @(
    (Join-Path $env:ProgramFiles "Tencent\QQNT\QQ.exe"),
    (Join-Path ${env:ProgramFiles(x86)} "Tencent\QQNT\QQ.exe")
) | Where-Object { $_ -and (Test-Path $_) }
$QQPath = $QQCandidates | Select-Object -First 1
$EnvFile = Join-Path $ProjectRoot ".env"
$Launcher = "$WorkDir\NapCatWinBootMain.exe"
$Inject   = "$WorkDir\NapCatWinBootHook.dll"
$MainJS   = "$WorkDir\napcat.mjs"
$LoadJS   = "$WorkDir\loadNapCat.js"
$PatchPkg = "$WorkDir\qqnt.json"

# QR code image path (generated by NapCat)
$QRImage = "$WorkDir\cache\qrcode.png"

# GitHub upload settings
$GithubRepo  = "MCPsDE/napcat-qrcode"
$ImagePath   = "qrcode.png"
$CommitMsg   = "Auto update QR code"
$GithubToken = $env:NAPCAT_QRCODE_GITHUB_TOKEN
if (-not $GithubToken -and (Test-Path $EnvFile)) {
    $TokenLine = Get-Content $EnvFile | Where-Object { $_ -match '^\s*NAPCAT_QRCODE_GITHUB_TOKEN\s*=' } | Select-Object -First 1
    if ($TokenLine) {
        $GithubToken = ($TokenLine -split "=", 2)[1].Trim().Trim('"').Trim("'")
    }
}

# Monitoring settings
$LogFile     = "$WorkDir\napcat_stdout.log"
$IdleTimeout = 60
$RestartWait = 30
# =================================================

# Mutex: prevent multiple instances
$mutex = New-Object System.Threading.Mutex($false, "Global\NapCatDaemon")
if (-not $mutex.WaitOne(0, $false)) {
    Write-Host "Another instance of NapCat Daemon is already running. Exiting." -ForegroundColor Red
    exit 1
}

# Initialize working directory and console encoding
Set-Location $WorkDir
[Console]::OutputEncoding = [System.Text.Encoding]::UTF8
$ErrorActionPreference = "Stop"

if (-not $QQPath) {
    throw "QQ.exe was not found under Program Files. Install QQ or set the path in NapCat_Daemon.ps1."
}

if (-not $GithubToken) {
    Write-Warning "NAPCAT_QRCODE_GITHUB_TOKEN is not configured. QR-code uploads to GitHub are disabled."
}

# Generate loadNapCat.js (same as original bat)
$MainJSFwd = $MainJS -replace '\\', '/'
"(async () => { await import(`"file:///$MainJSFwd`") })()" | Out-File -FilePath $LoadJS -Encoding ASCII

# Global state
$global:LastQRTime = $null
$global:LogWriter  = $null
$global:NapCatProcess = $null

function Start-NapCat {
    Write-Host "[$(Get-Date -Format 'HH:mm:ss')] Starting NapCat..."

    # Prepare process start info
    $procInfo = New-Object System.Diagnostics.ProcessStartInfo
    $procInfo.FileName = $Launcher
    $procInfo.Arguments = "`"$QQPath`" `"$Inject`""
    $procInfo.UseShellExecute = $false
    $procInfo.RedirectStandardOutput = $true
    $procInfo.RedirectStandardError = $true
    $procInfo.WorkingDirectory = $WorkDir

    # Set environment variables (identical to original bat)
    $procInfo.EnvironmentVariables["NAPCAT_PATCH_PACKAGE"] = $PatchPkg
    $procInfo.EnvironmentVariables["NAPCAT_LOAD_PATH"]     = $LoadJS
    $procInfo.EnvironmentVariables["NAPCAT_INJECT_PATH"]   = $Inject
    $procInfo.EnvironmentVariables["NAPCAT_LAUNCHER_PATH"] = $Launcher
    $procInfo.EnvironmentVariables["NAPCAT_MAIN_PATH"]     = $MainJS

    $global:NapCatProcess = New-Object System.Diagnostics.Process
    $global:NapCatProcess.StartInfo = $procInfo

    # Rotate old log file instead of clearing it (avoids file lock)
    if (Test-Path $LogFile) {
        Move-Item $LogFile "$LogFile.old" -Force -ErrorAction SilentlyContinue
    }

    # Create log writer (append mode, UTF-8)
    $global:LogWriter = [System.IO.StreamWriter]::new($LogFile, $true, [System.Text.Encoding]::UTF8)
    $global:LogWriter.AutoFlush = $true

    # Event handler for stdout/stderr
    $outputAction = {
        $line = $EventArgs.Data
        if ($line) {
            $global:LogWriter.WriteLine($line)
            Write-Host $line   # also echo to console
        }
    }
    $global:OutputEvent = Register-ObjectEvent -InputObject $global:NapCatProcess `
        -EventName 'OutputDataReceived' -Action $outputAction
    $global:ErrorEvent = Register-ObjectEvent -InputObject $global:NapCatProcess `
        -EventName 'ErrorDataReceived' -Action $outputAction

    $global:NapCatProcess.Start() | Out-Null
    $global:NapCatProcess.BeginOutputReadLine()
    $global:NapCatProcess.BeginErrorReadLine()

    Write-Host "Process PID: $($global:NapCatProcess.Id)"
    Start-Sleep 5
}

function Stop-NapCat {
    Write-Host "[$(Get-Date -Format 'HH:mm:ss')] Force killing all related processes..."

    # Kill all QQ.exe and NapCatWinBootMain.exe instances
    Get-Process -Name "QQ" -ErrorAction SilentlyContinue | Stop-Process -Force
    Get-Process -Name "NapCatWinBootMain" -ErrorAction SilentlyContinue | Stop-Process -Force
    Start-Sleep 2

    # Clean up the log writer
    if ($global:LogWriter) {
        try { $global:LogWriter.Close() } catch {}
        try { $global:LogWriter.Dispose() } catch {}
        $global:LogWriter = $null
    }

    # Unregister events
    if ($global:OutputEvent) { 
        Unregister-Event -SourceIdentifier $global:OutputEvent.Name -ErrorAction SilentlyContinue
        $global:OutputEvent = $null
    }
    if ($global:ErrorEvent) { 
        Unregister-Event -SourceIdentifier $global:ErrorEvent.Name -ErrorAction SilentlyContinue
        $global:ErrorEvent = $null
    }
}

function Test-IdleTimeout {
    if (-not (Test-Path $LogFile)) { return $false }
    $lastWrite = (Get-Item $LogFile).LastWriteTime
    return ((Get-Date) - $lastWrite).TotalSeconds -gt $IdleTimeout
}

function Watch-QRCode {
    if (Test-Path $QRImage) {
        $currentLastWrite = (Get-Item $QRImage).LastWriteTime
        if (-not $global:LastQRTime -or $currentLastWrite -gt $global:LastQRTime) {
            $global:LastQRTime = $currentLastWrite
            return $true
        }
    }
    return $false
}

function Upload-QRCode {
    if (-not $GithubToken) {
        Write-Warning "Skipping QR-code upload because NAPCAT_QRCODE_GITHUB_TOKEN is not configured."
        return
    }
    Write-Host "[$(Get-Date -Format 'HH:mm:ss')] New QR code detected, uploading to GitHub..."
    try {
        $base64 = [Convert]::ToBase64String([IO.File]::ReadAllBytes($QRImage))
        $uri = "https://api.github.com/repos/$GithubRepo/contents/$ImagePath"
        $headers = @{
            "Authorization" = "token $GithubToken"
            "Accept"        = "application/vnd.github.v3+json"
        }
        $sha = $null
        try {
            $resp = Invoke-RestMethod -Uri $uri -Headers $headers -Method Get
            $sha = $resp.sha
        } catch {}
        $body = @{
            message = $CommitMsg
            content = $base64
            branch  = "main"
        }
        if ($sha) { $body.sha = $sha }
        Invoke-RestMethod -Uri $uri -Headers $headers -Method Put -Body ($body | ConvertTo-Json) | Out-Null
        Write-Host "Upload successful! Access URL: https://raw.githubusercontent.com/$GithubRepo/main/$ImagePath?t=$(Get-Date -Format 'yyyyMMddHHmmss')"
    } catch {
        Write-Host "Upload failed: $_"
    }
}

# ========== Main daemon loop ==========
while ($true) {
    Start-NapCat
    $global:LastQRTime = $null

    while ($global:NapCatProcess -and !$global:NapCatProcess.HasExited) {
        if (Watch-QRCode) {
            Upload-QRCode
        }
        if (Test-IdleTimeout) {
            Write-Host "[$(Get-Date -Format 'HH:mm:ss')] Log timeout ${IdleTimeout}s detected, assuming offline. Restarting..."
            break
        }
        Start-Sleep 2
    }

    Stop-NapCat
    Write-Host "[$(Get-Date -Format 'HH:mm:ss')] Waiting ${RestartWait}s before restart..."
    Start-Sleep $RestartWait
}
